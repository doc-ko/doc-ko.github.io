#!/usr/bin/env python3
"""Regenerate src/lib/glyphs.js from open-licensed fonts.

The field emblem draws its symbols as SVG paths so they look the same on every
device and do not depend on installed fonts. This script cuts the outlines out
of the source fonts and writes them as path data in em units (y down, origin
at the left of the baseline), plus the ink bounds and advance of each glyph.

Usage: python3 scripts/extract-glyphs.py FONT_DIR

FONT_DIR must contain:
  STIXTwoText.ttf, STIXTwoText-Italic.ttf, STIXTwoMath.otf   (STIX Two, OFL 1.1)
  JetBrainsMono.woff2 (any regular-weight JetBrains Mono)     (OFL 1.1)

Needs fontTools (pip install fonttools brotli). The licences for the fonts are
kept in src/lib/glyph-licenses/.
"""
import json
import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

font_dir = Path(sys.argv[1])

# name -> (font file, character)
GLYPHS = {
    'schwa': ('STIXTwoText.ttf', 'ə'),
    'j': ('STIXTwoText.ttf', 'j'),
    'p': ('STIXTwoText.ttf', 'p'),
    'lambda': ('STIXTwoText.ttf', 'λ'),
    'zero': ('STIXTwoText.ttf', '0'),
    'equals': ('STIXTwoText.ttf', '='),
    'kItalic': ('STIXTwoText-Italic.ttf', 'k'),
    'sigma': ('STIXTwoMath.otf', '∑'),
    'dollar': ('JetBrainsMono.woff2', '$'),
}


def find_font(name):
    return font_dir / name


fonts = {}
out = {}
for key, (file, char) in GLYPHS.items():
    path = find_font(file)
    if path not in fonts:
        fonts[path] = TTFont(path)
    font = fonts[path]
    upm = font['head'].unitsPerEm
    glyph_name = font.getBestCmap()[ord(char)]
    glyph_set = font.getGlyphSet()

    # y is flipped so the path is in screen orientation, and scaled to 1 em
    scale = 1 / upm
    svg = SVGPathPen(glyph_set, ntos=lambda v: f'{v:.3f}'.rstrip('0').rstrip('.'))
    glyph_set[glyph_name].draw(TransformPen(svg, (scale, 0, 0, -scale, 0, 0)))

    bounds = BoundsPen(glyph_set)
    glyph_set[glyph_name].draw(bounds)
    xmin, ymin, xmax, ymax = bounds.bounds

    out[key] = {
        'd': svg.getCommands(),
        'adv': round(glyph_set[glyph_name].width * scale, 4),
        'xmin': round(xmin * scale, 4),
        'xmax': round(xmax * scale, 4),
        # heights above the baseline, in em (positive is up)
        'top': round(ymax * scale, 4),
        'bottom': round(ymin * scale, 4),
    }

target = Path(__file__).resolve().parent.parent / 'src' / 'lib' / 'glyphs.js'
target.write_text(
    '// Generated by scripts/extract-glyphs.py. Do not edit by hand.\n'
    '// Outlines from STIX Two (SIL OFL 1.1) and JetBrains Mono (SIL OFL 1.1);\n'
    '// licences are in src/lib/glyph-licenses/. Units are em, y down, origin at\n'
    '// the left of the baseline.\n'
    'export const glyphs = ' + json.dumps(out, ensure_ascii=False, indent=4) + ';\n'
)
print('wrote', target)
